  function getCurrentLanguage() {
    return localStorage.getItem('relovly_lang') || 'en';
  }

  function setLanguage(lang) {
    localStorage.setItem('relovly_lang', lang);
    document.documentElement.lang = lang;
    applyTranslations();
  }

  function t(key) {
    const lang = getCurrentLanguage();
    const dict = translations[lang] || translations.en;
    return dict[key] || translations.en[key] || key;
  }

  function translateCategoryName(englishName) {
    const key = categoryKeyMap[englishName];
    if (!key) return englishName;
    return t(key);
  }

  function applyTranslations() {
    // Any element with data-i18n="key"
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const translated = t(key);
      // If it has data-i18n-placeholder, apply to placeholder instead
      if (el.hasAttribute('data-i18n-placeholder')) {
        el.setAttribute('placeholder', translated);
      } else {
        el.textContent = translated;
      }
    });

    // Any element with data-i18n-placeholder alone
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      el.setAttribute('placeholder', t(key));
    });

    // Update page title if it has data-i18n-title
    const titleEl = document.querySelector('title[data-i18n-title]');
    if (titleEl) {
      titleEl.textContent = t(titleEl.getAttribute('data-i18n-title'));
    }

    // Dispatch an event so pages can react (e.g., re-render category names)
    window.dispatchEvent(new CustomEvent('relovly-lang-changed', { detail: { lang: getCurrentLanguage() } }));
  }

  // Auto-detect: on first visit, use browser language if supported
  function initLanguage() {
    const saved = localStorage.getItem('relovly_lang');
    if (saved) {
      document.documentElement.lang = saved;
    } else {
      const browserLang = (navigator.language || 'en').split('-')[0];
      const supported = Object.keys(translations);
      const useLang = supported.includes(browserLang) ? browserLang : 'en';
      localStorage.setItem('relovly_lang', useLang);
      document.documentElement.lang = useLang;
    }
  }

  // Expose to window
  window.relovlyI18n = {
    t,
    setLanguage,
    getCurrentLanguage,
    translateCategoryName,
    applyTranslations
  };

  // Initialize and apply on load
  initLanguage();
  document.addEventListener('DOMContentLoaded', applyTranslations);
  // In case DOM is already ready
  if (document.readyState !== 'loading') applyTranslations();
